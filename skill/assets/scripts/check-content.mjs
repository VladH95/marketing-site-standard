#!/usr/bin/env node
/**
 * Content gate — runs BEFORE `next build` (see package.json), so an incomplete
 * page fails the build and never reaches production. On Vercel the deploy is
 * marked failed and the old version stays live, which is exactly what you want
 * when the person publishing does not read code.
 *
 * ERRORS block the deploy. They are reserved for things that are (a) easy to
 * forget and (b) expensive to discover in production: missing frontmatter, a
 * cover image that does not exist, an FAQ too thin to emit valid FAQPage
 * schema, a long article with no summary.
 *
 * WARNINGS print and pass. They are quality nudges — an editor should read
 * them, but blocking a deploy over a 72-character title would train people to
 * ignore the gate entirely, which costs more than the title does.
 *
 * Every threshold comes from site.config.mjs. Do not edit this file per
 * project.
 *
 * Usage: node scripts/check-content.mjs
 * Requires: gray-matter
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import config from "../site.config.mjs";

const ROOT = process.cwd();
const PUBLIC_DIR = path.join(ROOT, "public");
const SAFE_SLUG = /^[a-z0-9][a-z0-9-]*$/;

let totalErrors = 0;
let totalWarnings = 0;
let totalFiles = 0;
const summary = [];

for (const [name, rules] of Object.entries(config.content ?? {})) {
  const dir = path.join(ROOT, rules.dir);
  if (!fs.existsSync(dir)) {
    console.log(`— skipping "${name}": ${rules.dir} does not exist`);
    continue;
  }

  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".md"));
  let checked = 0;

  for (const file of files) {
    const slug = file.replace(/\.md$/, "");
    const errs = [];
    const warns = [];

    // A stray filename never becomes a URL (the content loader filters on the
    // same pattern), so flag it rather than silently ignoring the file — a
    // typo'd filename is a page the author thinks is live and isn't.
    if (!SAFE_SLUG.test(slug)) {
      errs.push(`filename is not a valid slug (lowercase, a-z 0-9 - only)`);
    }

    const { data, content } = matter(
      fs.readFileSync(path.join(dir, file), "utf8")
    );

    // Drafts are excluded from routes, sitemap, and listings, so holding them
    // to the publish bar would just block the build on work in progress.
    if (data.draft === true) continue;
    checked++;

    // ── required frontmatter ────────────────────────────────────────────────
    for (const key of rules.required ?? []) {
      const v = data[key];
      const empty =
        v == null ||
        (typeof v === "string" && v.trim() === "") ||
        (Array.isArray(v) && v.length === 0);
      if (empty) errs.push(`missing/empty frontmatter: "${key}"`);
    }

    if (data.date && Number.isNaN(new Date(data.date).getTime())) {
      errs.push(`invalid date: "${data.date}"`);
    }

    // ── cover image must actually exist ─────────────────────────────────────
    // A missing cover degrades every share card and the Article schema, and it
    // is invisible until someone posts the link.
    const coverField = rules.coverField ?? "cover";
    const cover = data[coverField];
    if (typeof cover === "string" && cover.startsWith("/")) {
      if (!fs.existsSync(path.join(PUBLIC_DIR, cover))) {
        errs.push(`${coverField} file not found in /public: ${cover}`);
      }
    } else if (typeof cover === "string" && /^https?:\/\//.test(cover)) {
      errs.push(
        `${coverField} points at an external URL (${cover}) — host it in /public instead, external CDNs rot`
      );
    }

    // ── FAQ: complete pairs, enough of them ─────────────────────────────────
    const faqField = rules.faq?.field ?? "faq";
    const faqMin = rules.faq?.min ?? 0;
    const faq = data[faqField];
    if (faqMin > 0 || Array.isArray(faq)) {
      if (faqMin > 0 && !Array.isArray(faq)) {
        errs.push(`missing "${faqField}" — need ≥${faqMin} Q&A pairs for FAQPage schema`);
      } else if (Array.isArray(faq)) {
        if (faq.length < faqMin) {
          errs.push(
            `${faqField} has ${faq.length} item(s) — need ≥${faqMin} for FAQPage schema`
          );
        }
        faq.forEach((f, i) => {
          const q = typeof f?.question === "string" && f.question.trim();
          const a = typeof f?.answer === "string" && f.answer.trim();
          if (!q || !a) errs.push(`${faqField}[${i}] is missing a question or answer`);
        });
      }
    }

    const words = content.split(/\s+/).filter(Boolean).length;

    // ── takeaways on long-form ──────────────────────────────────────────────
    const tkRules = rules.takeaways;
    if (tkRules?.min > 0 && words >= (tkRules.minWords ?? 0)) {
      const field = tkRules.field ?? "takeaways";
      const tk = data[field];
      if (!Array.isArray(tk) || tk.length < tkRules.min) {
        errs.push(
          `long-form (${words} words) needs ≥${tkRules.min} key takeaways — add a "${field}:" list to the frontmatter`
        );
      } else {
        tk.forEach((t, i) => {
          if (typeof t !== "string" || !t.trim()) errs.push(`${field}[${i}] is empty`);
        });
        if (tkRules.max && tk.length > tkRules.max) {
          warns.push(`${tk.length} takeaways — keep to ${tkRules.min}–${tkRules.max} for scannability`);
        }
      }
    }

    // ── warnings ────────────────────────────────────────────────────────────
    const w = rules.warn ?? {};

    // Search results display seoTitle when present, so measure that one.
    const serpTitle = typeof data.seoTitle === "string" ? data.seoTitle : data.title;
    if (w.titleMaxChars && typeof serpTitle === "string" && serpTitle.length > w.titleMaxChars) {
      warns.push(
        `title is ${serpTitle.length} chars (>${w.titleMaxChars} truncates in search results — add a shorter "seoTitle:")`
      );
    }

    if (w.descriptionChars && typeof data.description === "string") {
      const [lo, hi] = w.descriptionChars;
      const n = data.description.trim().length;
      if (n < lo || n > hi) warns.push(`description is ${n} chars (ideal ${lo}–${hi})`);
    }

    if (w.minH2) {
      const h2 = (content.match(/^##\s+/gm) || []).length;
      if (h2 < w.minH2) {
        warns.push(`only ${h2} H2 heading(s) — ≥${w.minH2} helps both search and AI extraction`);
      }
    }

    if (w.minWords && words < w.minWords) {
      warns.push(`${words} words — looks thin (<${w.minWords})`);
    }

    if (w.requireInternalLink) {
      // Root-relative page links, ignoring asset paths.
      const pageLinks = (content.match(/\]\(\/(?!images\/|og\/|icons\/|fonts\/)[^)\s]*\)/g) || []).length;
      if (pageLinks < 1) {
        warns.push(`no internal links — cross-link to a service or another article`);
      }
    }

    if (w.flagLooseQuotes) {
      // Quotes written as *"…"* or as a bare quoted line render as ordinary
      // body copy and read as filler. As `> blockquote` they become pull-quotes
      // — more scannable, and the shape AI answer engines lift as a citation.
      const nonQuoteLines = content.split("\n").filter((l) => !l.trim().startsWith(">"));
      const italicQuotes =
        nonQuoteLines.join("\n").match(/(?<!\*)\*["“][^*\n]{12,}["”]\*(?!\*)/g) || [];
      const standaloneQuotes = nonQuoteLines.filter((l) =>
        /^["“][^"“”]{16,}["”]$/.test(l.trim())
      ).length;
      const loose = italicQuotes.length + standaloneQuotes;
      if (loose > 0) {
        warns.push(`${loose} quote(s) look unmarked — use \`> quote\` so they render as pull-quotes`);
      }
    }

    if (errs.length) {
      totalErrors += errs.length;
      console.log(`\n❌ ${name}/${slug}`);
      errs.forEach((e) => console.log(`     ERROR: ${e}`));
      warns.forEach((x) => console.log(`     warn:  ${x}`));
    } else if (warns.length) {
      totalWarnings += warns.length;
      console.log(`\n⚠️  ${name}/${slug}`);
      warns.forEach((x) => console.log(`     warn:  ${x}`));
    }
  }

  totalFiles += checked;
  summary.push(`${checked} ${name}`);
}

console.log(
  `\n— content gate: ${summary.join(" + ") || "nothing to check"} · ${totalErrors} error(s) · ${totalWarnings} warning(s) —`
);

if (totalErrors > 0) {
  console.error(`\n✖ Content gate FAILED — fix the ${totalErrors} error(s) above. Deploy blocked.\n`);
  process.exit(1);
}
console.log(`✓ Content gate passed (${totalFiles} file(s)).\n`);
